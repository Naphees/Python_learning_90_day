# Data Types
# getting the data type
print(type(3))

# Setting the Data Type
x = 10 # int
print(x)

x = "Hello" # str
print(x)

x = 20.3 # float
print(x)

x = 1j # complex
print(x)

x = ["apple","banana", "cherry"] # list
print(x)

x = ("apple","banana",2) # tuple
print(x)

x = range(5) # range
print(x)


x = {"name" :"Sigma", "age": 26} # dict
print(x)

x = {"apple","banana"} # set
print(x)

x = frozenset({"apple","banana","cherry"}) # frozerset
print(x)


x = True # bool
print(x)

x = b"Hello" # bytes
print(x)

x = bytearray(5) # bytearray
print(x)

x = memoryview(bytes(5)) # memoryview
print(x)

x = None # NoneType
print(x)