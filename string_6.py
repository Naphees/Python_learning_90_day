#  String concatenation 
a = "Hello"
b = 'World'
c = a + b
print(c)
c = a + " " + b
print(c)


# String format

a = 3
b = f"Lovey is {a}"
print(b)
#  format with decimal
price = 35
print(f"Apple is {price:.2f} per piece.")

