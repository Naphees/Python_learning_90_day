# Operators 

# Arithmetic 
print(5 + 3) # Addition = 8
print(5 - 3) # Subtraction = 2
print(5 * 3) #  multiple  = 15
print(5 / 3) # Division = 1.666 something, return always float
print(5 // 3) # floor division = 1 return, always integer
print(5 % 3) # modulus = 2
print(5 ** 3) # Exponentiation  = 125

