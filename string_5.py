# String Slice
# return range of characters
a = "Python"
print(a[0:1]) # P

print(a[:5]) # Pytho

print(a[-1:]) # n
print(a[:-1]) # Pytho
print(a[-5:-1]) # ytho


# String modifie

b = ' Lovely, good, Bro '
# upper()
print(b.upper())
# lower()
print(b.lower())
# remove whitespace
print(b.strip())

# replace string 
print(b.replace("Lovely","Sigma"))

# Split convert string to list
print(b.split(","))

